-- 七、登录会话与首次设置

-- 登录会话。库里只存令牌的 SHA-256（char(64)），不存令牌本身；
-- 绝对过期时间落 expire_time，空闲超时（设置要求立即生效）在请求时按设置计算；
-- 吊销用 revoked_time，不删行。last_active_time 由应用节流更新（约每分钟一次）。
CREATE TABLE sand_system_session (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id          bigint       NOT NULL,
    token_hash       char(64)     NOT NULL,                 -- SHA-256(32 字节随机令牌) 的十六进制
    auth_method      varchar(16)  NOT NULL,                 -- password / bootstrap / dev
    ip               inet         NOT NULL,
    location         varchar(64)  NOT NULL DEFAULT '',      -- 只到城市
    user_agent       varchar(512) NOT NULL DEFAULT '',
    device_label     varchar(64)  NOT NULL DEFAULT '',      -- 例：Mac 上的 Chrome
    create_time      timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_active_time timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expire_time      timestamptz(0) NOT NULL,               -- 绝对过期（登录保持天数）
    revoked_time     timestamptz(0) NULL,
    revoked_reason   varchar(24)  NULL,
    CONSTRAINT pk_sand_system_session PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_session_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_sand_system_session_token_hash
        CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sand_system_session_auth_method
        CHECK (auth_method IN ('password', 'bootstrap', 'dev')),
    CONSTRAINT ck_sand_system_session_expire CHECK (expire_time > create_time),
    CONSTRAINT ck_sand_system_session_revoked
        CHECK ((revoked_time IS NULL AND revoked_reason IS NULL)
               OR (revoked_time IS NOT NULL AND revoked_reason IN
                   ('logout', 'kicked', 'password_changed',
                    'password_reset', 'user_disabled', 'user_deleted'))),
    CONSTRAINT fk_sand_system_session_user
        FOREIGN KEY (user_id) REFERENCES sand_system_user (id) ON DELETE CASCADE
);
COMMENT ON TABLE sand_system_session IS '登录会话；只存令牌 SHA-256；吊销用 revoked_time 不删行';
CREATE INDEX ix_sand_system_session_user_active
    ON sand_system_session (user_id, last_active_time DESC) WHERE revoked_time IS NULL;
CREATE INDEX ix_sand_system_session_expire_time ON sand_system_session (expire_time);

-- 一次性口令（首次设置向导第 1 步用）。明文只在终端显示一次；
-- 24 小时有效；连错 5 次、重新生成、或向导第 1 步新密码保存成功（used_time）即失效。
CREATE TABLE sand_system_bootstrap_credential (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id      bigint       NOT NULL,
    secret_hash  varchar(255) NOT NULL,                     -- Argon2id；明文不落库
    expire_time  timestamptz(0) NOT NULL,                   -- 生成后 24 小时
    failed_count smallint     NOT NULL DEFAULT 0,
    used_time    timestamptz(0) NULL,                       -- 向导第 1 步新密码保存成功才写
    revoked_time timestamptz(0) NULL,                       -- 连错 5 次 / 重新生成
    create_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sand_system_bootstrap_credential PRIMARY KEY (id),
    CONSTRAINT ck_sand_system_bootstrap_credential_failed CHECK (failed_count BETWEEN 0 AND 5),
    CONSTRAINT ck_sand_system_bootstrap_credential_expire CHECK (expire_time > create_time),
    CONSTRAINT fk_sand_system_bootstrap_credential_user
        FOREIGN KEY (user_id) REFERENCES sand_system_user (id) ON DELETE CASCADE
);
COMMENT ON TABLE sand_system_bootstrap_credential IS '首次设置的一次性口令；每用户同时最多一条未用未作废';
CREATE UNIQUE INDEX uk_sand_system_bootstrap_credential_active
    ON sand_system_bootstrap_credential (user_id)
    WHERE used_time IS NULL AND revoked_time IS NULL;

-- 安装与首次设置状态（单行，CHECK id=1）。生产包启动时读它判断是否已初始化；
-- setup_state：pending_password（第 1 步未完成）→ pending_basics（第 2 步未完成）→ completed。
CREATE TABLE sand_system_installation (
    id                  smallint PRIMARY KEY DEFAULT 1,
    host_version        varchar(32) NOT NULL,
    install_time        timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    setup_state         varchar(24)  NOT NULL DEFAULT 'pending_password',
    setup_complete_time timestamptz(0) NULL,
    update_time         timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sand_system_installation_single CHECK (id = 1),
    CONSTRAINT ck_sand_system_installation_setup_state
        CHECK (setup_state IN ('pending_password', 'pending_basics', 'completed')),
    CONSTRAINT ck_sand_system_installation_complete
        CHECK ((setup_state = 'completed') = (setup_complete_time IS NOT NULL))
);
COMMENT ON TABLE sand_system_installation IS '安装与首次设置状态；单行（id=1），由初始化流程创建';

-- 升级与插件申请：网页进程只插入和查询，
-- 独立执行进程用 SELECT ... FOR UPDATE SKIP LOCKED 认领；全系统同时只允许一个未完成申请。
CREATE TABLE sand_system_lifecycle_request (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id               uuid         NOT NULL DEFAULT gen_random_uuid(),
    kind                    varchar(24)  NOT NULL,          -- plugin_install/plugin_upgrade/plugin_uninstall/plugin_upgrade_batch/system_upgrade
    target_code             varchar(64)  NOT NULL,          -- 插件标识；系统升级写 host；批量升级写 *
    from_version            varchar(32)  NULL,              -- Semver
    to_version              varchar(32)  NULL,              -- Semver
    source                  varchar(16)  NOT NULL,          -- official / upload
    package_file_id         bigint       NULL,              -- 上传的安装包文件
    package_sha256          char(64)     NULL,
    signature_key_id        varchar(64)  NULL,              -- 验签通过的 Ed25519 公钥标识
    signature_verified_time timestamptz(0) NULL,
    purge_data              boolean      NOT NULL DEFAULT false, -- 卸载时是否同时删除插件数据
    items                   jsonb        NULL,              -- 批量申请的逐项进度 [{code,from_version,to_version,state}]，仅 plugin_upgrade_batch 使用，必须为非空数组
    state                   varchar(16)  NOT NULL DEFAULT 'queued',
    stage                   varchar(32)  NULL,              -- 执行阶段的人话描述
    progress                smallint     NOT NULL DEFAULT 0,
    rolled_back             boolean      NOT NULL DEFAULT false, -- 失败且已自动恢复
    error_code              varchar(64)  NULL,
    error_message           varchar(500) NULL,
    requested_by            bigint       NOT NULL,          -- 申请人（仅超管可申请）
    request_id              varchar(64)  NOT NULL,          -- 客户端幂等键
    executor_id             varchar(128) NULL,              -- 认领执行的进程标识
    heartbeat_time          timestamptz(0) NULL,
    create_time             timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    start_time              timestamptz(0) NULL,
    finish_time             timestamptz(0) NULL,
    CONSTRAINT pk_sand_system_lifecycle_request PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_lifecycle_request_public_id UNIQUE (public_id),
    CONSTRAINT uk_sand_system_lifecycle_request_request_id UNIQUE (request_id),
    CONSTRAINT ck_sand_system_lifecycle_request_target_code
        CHECK (target_code = '*' OR target_code ~ '^[a-z0-9][a-z0-9_-]{0,63}$'),  -- 插件标识、host 或批量占位 *
    CONSTRAINT ck_sand_system_lifecycle_request_kind
        CHECK (kind IN ('plugin_install', 'plugin_upgrade', 'plugin_uninstall',
                        'plugin_upgrade_batch', 'system_upgrade')),
    -- 批量升级申请：kind=plugin_upgrade_batch 当且仅当 target_code='*' 且 items 为非空数组
    CONSTRAINT ck_sand_system_lifecycle_request_batch
        CHECK ((kind = 'plugin_upgrade_batch') = (target_code = '*')
               AND (kind = 'plugin_upgrade_batch') = (items IS NOT NULL)),
    CONSTRAINT ck_sand_system_lifecycle_request_items
        CHECK (items IS NULL
               OR (jsonb_typeof(items) = 'array' AND jsonb_array_length(items) > 0)),
    CONSTRAINT ck_sand_system_lifecycle_request_source CHECK (source IN ('official', 'upload')),
    CONSTRAINT ck_sand_system_lifecycle_request_state
        CHECK (state IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
    CONSTRAINT ck_sand_system_lifecycle_request_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_sand_system_lifecycle_request_semver
        CHECK ((from_version IS NULL OR from_version ~
                '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$')
               AND (to_version IS NULL OR to_version ~
                '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$')),
    CONSTRAINT ck_sand_system_lifecycle_request_package_sha256
        CHECK (package_sha256 IS NULL OR package_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sand_system_lifecycle_request_upload
        CHECK (source <> 'upload' OR package_file_id IS NOT NULL),
    CONSTRAINT fk_sand_system_lifecycle_request_package_file
        FOREIGN KEY (package_file_id) REFERENCES sand_system_file (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sand_system_lifecycle_request_requested_by
        FOREIGN KEY (requested_by) REFERENCES sand_system_user (id) ON DELETE RESTRICT
);
COMMENT ON TABLE sand_system_lifecycle_request IS '升级与插件申请；网页只提交，独立进程执行；同时只允许一个未完成';
-- 全系统同时只允许一个 queued/running 的申请（单飞）
CREATE UNIQUE INDEX uk_sand_system_lifecycle_request_single_flight
    ON sand_system_lifecycle_request ((true)) WHERE state IN ('queued', 'running');
-- 执行进程认领待处理申请
CREATE INDEX ix_sand_system_lifecycle_request_pending
    ON sand_system_lifecycle_request (create_time, id) WHERE state IN ('queued', 'running');
CREATE INDEX ix_sand_system_lifecycle_request_create_time
    ON sand_system_lifecycle_request (create_time DESC);

-- 迁移账本（全仓唯一）。每份迁移文件头声明所属版本与 compatible/breaking，
-- CI 据此卡 Semver；迁移只能由命令行执行，HTTP 与任务进程运行期不建表。
CREATE TABLE sand_system_schema_migration (
    version         varchar(128) PRIMARY KEY,               -- 迁移编号/文件名
    checksum        char(64)     NOT NULL,                   -- 迁移文件 SHA-256
    release_version varchar(32)  NOT NULL,                   -- 随哪个宿主版本发布
    applied_time    timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    execution_ms    integer      NOT NULL DEFAULT 0,
    CONSTRAINT ck_sand_system_schema_migration_checksum
        CHECK (checksum ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sand_system_schema_migration_execution_ms CHECK (execution_ms >= 0)
);
COMMENT ON TABLE sand_system_schema_migration IS '迁移账本；全仓唯一；记录版本归属与校验和';

-- 八、循环外键补加（本事务内、全部 CREATE TABLE 完成之后执行）
-- sand_system_user 与 sand_system_dept / sand_system_post / sand_system_file
-- 存在互相引用：
--   user.dept_id → dept.id        dept.leader_id → user.id
--   user.post_id → post.id        （post.created_by → user.id 已内联）
--   user.avatar_file_id → file.id file.uploader_id → user.id
-- 处理方式：user 表上的这三个外键延后到这里用 ALTER TABLE 补加；
-- 反方向的外键（dept.leader_id、file.uploader_id、各 created_by/updated_by）
-- 在建表时已内联声明，被引用表均先建好。全部在同一事务内完成。
ALTER TABLE sand_system_user
    ADD CONSTRAINT fk_sand_system_user_dept_id
        FOREIGN KEY (dept_id) REFERENCES sand_system_dept (id) ON DELETE RESTRICT,
    ADD CONSTRAINT fk_sand_system_user_post_id
        FOREIGN KEY (post_id) REFERENCES sand_system_post (id) ON DELETE SET NULL,
    ADD CONSTRAINT fk_sand_system_user_avatar_file_id
        FOREIGN KEY (avatar_file_id) REFERENCES sand_system_file (id) ON DELETE SET NULL;
