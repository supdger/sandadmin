-- sandadmin 1.x 宿主 · 基线迁移 0001
-- 迁移版本（release_version）：1.0.0；兼容标记：compatible
-- 目标数据库：PostgreSQL 15+；由迁移执行器在一个事务里执行，本文件不写事务语句，失败整体回滚。
-- 1.x 全新安装的第 1 号基线迁移，不含删除结构语句；不写入种子数据
-- （sand_system_installation 单行由初始化流程创建）。全部时间列为 timestamptz(0)；
-- 表名 sand_system_ 前缀、资源名单数；约束命名 pk_/uk_/ix_/fk_/ck_ + 表名 + 列名。

-- 一、身份与权限（sand_system_user / dept / post / role 及关联表、登录限流）

-- 后台管理账号。软删除（delete_time）：删除后手机号与登录账号立刻空出来、dept_id 置空，
-- 但「不重复」只和未删除的用户比（部分唯一索引）。
CREATE TABLE sand_system_user (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    username                varchar(20)    NULL,              -- 登录账号；空则用手机号登录
    phone                   varchar(20)    NOT NULL,           -- 11 位手机号，同时可作登录账号
    nickname                varchar(20)    NOT NULL,           -- 姓名
    email                   varchar(128)   NULL,
    avatar_file_id          bigint         NULL,              -- 外键延后到文件末尾补加（与 sand_system_file 互相引用）
    dept_id                 bigint         NULL,               -- 外键延后到文件末尾补加（与 sand_system_dept 互相引用）；软删时由应用层置空
    post_id                 bigint         NULL,               -- 同上，引用 sand_system_post
    password_hash           varchar(255)   NOT NULL,           -- Argon2id 哈希；库里不存明文
    password_changed_time   timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    password_policy_tier    varchar(16)    NOT NULL DEFAULT 'unknown', -- 口令规则档位：temp/normal/admin/unknown
    must_change_password    boolean        NOT NULL DEFAULT false,
    must_change_reason      varchar(24)    NULL,               -- temp/policy_upgrade/system_upgrade
    is_super                boolean        NOT NULL DEFAULT false,
    is_admin                boolean        NOT NULL DEFAULT false,
    authz_version           integer        NOT NULL DEFAULT 1, -- 权限版本号，改权限时自增使缓存失效
    status                  smallint       NOT NULL DEFAULT 1, -- 1 启用 / 2 停用
    last_login_time         timestamptz(0) NULL,
    create_time             timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time             timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time             timestamptz(0) NULL,
    created_by              bigint         NULL,              -- 指向 sand_system_user.id，建表时内联外键
    updated_by              bigint         NULL,
    CONSTRAINT pk_sand_system_user PRIMARY KEY (id),
    CONSTRAINT ck_sand_system_user_username_format
        CHECK (username IS NULL OR username ~ '^[A-Za-z0-9_]{4,20}$'),
    -- 纯 11 位数字的登录账号必须等于本人手机号，堵住「甲的登录账号 = 乙的手机号」
    CONSTRAINT ck_sand_system_user_username_not_other_phone
        CHECK (username IS NULL OR username !~ '^[0-9]{11}$' OR username = phone),
    CONSTRAINT ck_sand_system_user_phone_format
        CHECK (phone ~ '^1[0-9]{10}$'),
    CONSTRAINT ck_sand_system_user_email_format
        CHECK (email IS NULL OR email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_sand_system_user_password_tier
        CHECK (password_policy_tier IN ('temp', 'normal', 'admin', 'unknown')),
    CONSTRAINT ck_sand_system_user_must_change_reason
        CHECK (must_change_reason IS NULL
               OR must_change_reason IN ('temp', 'policy_upgrade', 'system_upgrade')),
    CONSTRAINT ck_sand_system_user_must_change_link
        CHECK ((must_change_password AND must_change_reason IS NOT NULL)
               OR (NOT must_change_password AND must_change_reason IS NULL)),
    CONSTRAINT ck_sand_system_user_status CHECK (status IN (1, 2)),
    -- 未软删用户必有部门；软删用户允许 dept_id 为空（应用层置空，CHECK 兜底未删侧）
    CONSTRAINT ck_sand_system_user_dept_id
        CHECK (delete_time IS NOT NULL OR dept_id IS NOT NULL),
    CONSTRAINT fk_sand_system_user_created_by
        FOREIGN KEY (created_by) REFERENCES sand_system_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_sand_system_user_updated_by
        FOREIGN KEY (updated_by) REFERENCES sand_system_user (id) ON DELETE SET NULL
);
COMMENT ON TABLE sand_system_user IS '后台管理账号；软删除，手机号与登录账号对未删除用户唯一（部分唯一索引）';
-- 登录账号不区分大小写唯一；手机号唯一；均只约束未删除用户
CREATE UNIQUE INDEX uk_sand_system_user_username
    ON sand_system_user (lower(username)) WHERE delete_time IS NULL;
CREATE UNIQUE INDEX uk_sand_system_user_phone
    ON sand_system_user (phone) WHERE delete_time IS NULL;
-- 列表页默认「最新添加在前」及按部门、最近登录筛选/排序
CREATE INDEX ix_sand_system_user_create_time
    ON sand_system_user (create_time DESC, id DESC) WHERE delete_time IS NULL;
CREATE INDEX ix_sand_system_user_dept_id
    ON sand_system_user (dept_id) WHERE delete_time IS NULL;
-- 岗位页人数统计与删除岗位时的 SET NULL 反查
CREATE INDEX ix_sand_system_user_post_id
    ON sand_system_user (post_id) WHERE delete_time IS NULL;
CREATE INDEX ix_sand_system_user_last_login_time
    ON sand_system_user (last_login_time) WHERE delete_time IS NULL;

-- 部门（树形）。根节点 parent_id 为 NULL；同一上级下名称唯一
-- （UNIQUE NULLS NOT DISTINCT，PostgreSQL 15 特性）。硬删除：有人或有下级时被外键拦住。
CREATE TABLE sand_system_dept (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    parent_id    bigint      NULL,                          -- 根节点为 NULL；自引用外键
    name         varchar(30) NOT NULL,
    leader_id    bigint      NULL,                          -- 负责人，引用 sand_system_user
    phone        varchar(20) NULL,                          -- 联系电话
    sort         integer     NOT NULL DEFAULT 0,
    status       smallint    NOT NULL DEFAULT 1,            -- 1 启用 / 2 停用
    create_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by   bigint      NULL,
    updated_by   bigint      NULL,
    CONSTRAINT pk_sand_system_dept PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_dept_parent_name
        UNIQUE NULLS NOT DISTINCT (parent_id, name),
    CONSTRAINT ck_sand_system_dept_parent_self
        CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT ck_sand_system_dept_status CHECK (status IN (1, 2)),
    CONSTRAINT fk_sand_system_dept_parent
        FOREIGN KEY (parent_id) REFERENCES sand_system_dept (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sand_system_dept_leader
        FOREIGN KEY (leader_id) REFERENCES sand_system_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_sand_system_dept_created_by
        FOREIGN KEY (created_by) REFERENCES sand_system_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_sand_system_dept_updated_by
        FOREIGN KEY (updated_by) REFERENCES sand_system_user (id) ON DELETE SET NULL
);
COMMENT ON TABLE sand_system_dept IS '部门树；根节点 parent_id 为 NULL，同一上级下名称唯一；硬删除由外键保护';
CREATE INDEX ix_sand_system_dept_parent_sort ON sand_system_dept (parent_id, sort);

-- 岗位。一人一岗：挂在 sand_system_user.post_id 上，删除岗位自动置空（SET NULL）。
CREATE TABLE sand_system_post (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    name         varchar(20) NOT NULL,
    remark       varchar(100) NULL,
    sort         integer     NOT NULL DEFAULT 0,
    status       smallint    NOT NULL DEFAULT 1,            -- 1 启用 / 2 停用
    create_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by   bigint      NULL,
    updated_by   bigint      NULL,
    CONSTRAINT pk_sand_system_post PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_post_name UNIQUE (name),
    CONSTRAINT ck_sand_system_post_status CHECK (status IN (1, 2)),
    CONSTRAINT fk_sand_system_post_created_by
        FOREIGN KEY (created_by) REFERENCES sand_system_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_sand_system_post_updated_by
        FOREIGN KEY (updated_by) REFERENCES sand_system_user (id) ON DELETE SET NULL
);
COMMENT ON TABLE sand_system_post IS '岗位；名称唯一；删除岗位时用户的 post_id 自动置空';

-- 角色。code 由后端生成、界面不展示；data_scope 为字符串枚举。
CREATE TABLE sand_system_role (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    name           varchar(20) NOT NULL,
    code           varchar(64) NOT NULL,                    -- 系统自动生成，界面不展示
    remark         varchar(100) NULL,
    data_scope     varchar(16) NOT NULL DEFAULT 'dept_and_child',
    is_system      boolean     NOT NULL DEFAULT false,      -- 系统自带角色，应用层拒绝删除/停用
    is_super       boolean     NOT NULL DEFAULT false,      -- 全库唯一超级管理员角色；用户表 is_super 由是否持有本角色物化、同事务同步
    status         smallint    NOT NULL DEFAULT 1,          -- 1 启用 / 2 停用
    authz_version  integer     NOT NULL DEFAULT 1,          -- 权限版本号
    create_time    timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time    timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     bigint      NULL,
    updated_by     bigint      NULL,
    CONSTRAINT pk_sand_system_role PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_role_name UNIQUE (name),
    CONSTRAINT uk_sand_system_role_code UNIQUE (code),
    CONSTRAINT ck_sand_system_role_data_scope
        CHECK (data_scope IN ('all', 'dept_and_child', 'dept', 'self', 'custom')),
    CONSTRAINT ck_sand_system_role_status CHECK (status IN (1, 2)),
    CONSTRAINT fk_sand_system_role_created_by
        FOREIGN KEY (created_by) REFERENCES sand_system_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_sand_system_role_updated_by
        FOREIGN KEY (updated_by) REFERENCES sand_system_user (id) ON DELETE SET NULL
);
COMMENT ON TABLE sand_system_role IS '角色；名称与编码唯一；data_scope 控制能看哪些数据';
-- 全库只允许一个超级管理员角色
CREATE UNIQUE INDEX uk_sand_system_role_is_super
    ON sand_system_role ((true)) WHERE is_super;

-- 用户-角色关联。复合主键，同一对关系不会重复。
CREATE TABLE sand_system_user_role (
    user_id  bigint NOT NULL,
    role_id  bigint NOT NULL,
    CONSTRAINT pk_sand_system_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_sand_system_user_role_user
        FOREIGN KEY (user_id) REFERENCES sand_system_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_sand_system_user_role_role
        FOREIGN KEY (role_id) REFERENCES sand_system_role (id) ON DELETE CASCADE
);
COMMENT ON TABLE sand_system_user_role IS '用户与角色的多对多关联';
CREATE INDEX ix_sand_system_user_role_role_id ON sand_system_user_role (role_id);

-- 角色-部门关联（data_scope = custom 时的指定部门）。复合主键。
-- 部门删除时级联去掉，对应「数据范围里同步去掉它」的规格。
CREATE TABLE sand_system_role_dept (
    role_id  bigint NOT NULL,
    dept_id  bigint NOT NULL,
    CONSTRAINT pk_sand_system_role_dept PRIMARY KEY (role_id, dept_id),
    CONSTRAINT fk_sand_system_role_dept_role
        FOREIGN KEY (role_id) REFERENCES sand_system_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_sand_system_role_dept_dept
        FOREIGN KEY (dept_id) REFERENCES sand_system_dept (id) ON DELETE CASCADE
);
COMMENT ON TABLE sand_system_role_dept IS '角色「指定部门」数据范围的部门清单';
CREATE INDEX ix_sand_system_role_dept_dept_id ON sand_system_role_dept (dept_id);

-- 角色-权限关联。按权限标识字符串关联（不按菜单编号），插件卸载重装后勾选保留。
CREATE TABLE sand_system_role_permission (
    role_id          bigint      NOT NULL,
    permission_code  varchar(96) NOT NULL,                  -- 例：system:user:index
    CONSTRAINT pk_sand_system_role_permission PRIMARY KEY (role_id, permission_code),
    CONSTRAINT ck_sand_system_role_permission_code
        CHECK (permission_code ~ '^[a-z0-9][a-z0-9_.:-]{1,95}$'),
    CONSTRAINT fk_sand_system_role_permission_role
        FOREIGN KEY (role_id) REFERENCES sand_system_role (id) ON DELETE CASCADE
);
COMMENT ON TABLE sand_system_role_permission IS '角色持有的权限标识清单；插件卸载后行保留，读取时按清单过滤';
CREATE INDEX ix_sand_system_role_permission_code ON sand_system_role_permission (permission_code);

-- 登录限流与锁定计数。计数键是「输入内容的哈希」（账号不存在也能计数，且不泄露账号是否存在）。
CREATE TABLE sand_system_auth_throttle (
    subject_kind        varchar(8)    NOT NULL,             -- account / device / ip
    subject_hash        char(64)      NOT NULL,             -- SHA-256 十六进制
    failed_count        integer       NOT NULL DEFAULT 0,
    first_failed_time   timestamptz(0) NOT NULL,
    last_failed_time    timestamptz(0) NOT NULL,
    locked_until_time   timestamptz(0) NULL,                -- 锁定截止；过期自动解锁
    CONSTRAINT pk_sand_system_auth_throttle PRIMARY KEY (subject_kind, subject_hash),
    CONSTRAINT ck_sand_system_auth_throttle_subject_kind
        CHECK (subject_kind IN ('account', 'device', 'ip')),
    CONSTRAINT ck_sand_system_auth_throttle_subject_hash
        CHECK (subject_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sand_system_auth_throttle_failed_count CHECK (failed_count >= 0)
);
COMMENT ON TABLE sand_system_auth_throttle IS '登录失败计数与锁定；清理任务删除过期行；配 Redis 时可改走 Redis，本表始终存在兜底';
CREATE INDEX ix_sand_system_auth_throttle_last_failed_time
    ON sand_system_auth_throttle (last_failed_time);

-- 登录点选验证码挑战；id 用 uuid，挑战编号对外不可猜
CREATE TABLE sand_system_captcha (
    id            uuid           PRIMARY KEY DEFAULT gen_random_uuid(),
    answer_hash   char(64)       NOT NULL,                  -- 点选答案的 SHA-256，不存明文坐标
    expire_time   timestamptz(0) NOT NULL,                  -- 挑战 5 分钟有效
    used_time     timestamptz(0) NULL,                      -- 校验通过即写，用过即作废防重放
    create_time   timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sand_system_captcha_answer_hash
        CHECK (answer_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sand_system_captcha_expire
        CHECK (expire_time > create_time)
);
COMMENT ON TABLE sand_system_captcha IS '登录点选验证码挑战；只存答案哈希，用过即作废，过期由清理任务删除';
CREATE INDEX ix_sand_system_captcha_expire_time
    ON sand_system_captcha (expire_time);

-- 二、菜单与设置（默认定义在随包静态清单，库里只存覆盖与自建）

-- 菜单覆盖表：只存管理员对清单菜单的改动（改名、图标、换组、排序、显隐）。
-- 列为 NULL 表示这一项没改；「恢复默认」清空对应行；插件卸载默认保留，勾选
-- 「同时删除数据」卸载时由应用删除。
CREATE TABLE sand_system_menu_override (
    menu_key    varchar(128) PRIMARY KEY,                   -- 清单里的菜单键（含插件前缀）
    title       varchar(6)  NULL,
    icon        varchar(64) NULL,
    parent_key  varchar(128) NULL,                          -- 调整后的上级菜单键
    sort        integer     NULL,
    visible     boolean     NULL,
    create_time timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE sand_system_menu_override IS '对随包菜单清单的覆盖（改名/图标/换组/排序/显隐）；列为 NULL 表示未改';

-- 自建菜单：分组（group）与外部链接（link）两种。menu_key 由应用生成，
-- 供子级 parent_key 引用；parent_key 指向合并后的菜单键空间（清单键或自建键），
-- 清单在静态文件里无法建外键，故不建。
CREATE TABLE sand_system_menu_custom (
    menu_key    varchar(128) PRIMARY KEY,
    kind        varchar(8)   NOT NULL,                     -- group / link
    title       varchar(6)   NOT NULL,
    icon        varchar(64)  NULL,
    parent_key  varchar(128) NULL,
    url         varchar(2048) NULL,                        -- 链接类自建菜单的导航地址（非任务执行目标）
    sort        integer      NOT NULL DEFAULT 0,
    visible     boolean      NOT NULL DEFAULT true,
    create_time timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  bigint       NULL,
    updated_by  bigint       NULL,
    CONSTRAINT ck_sand_system_menu_custom_kind CHECK (kind IN ('group', 'link')),
    CONSTRAINT ck_sand_system_menu_custom_url
        CHECK ((kind = 'link' AND url IS NOT NULL AND url ~ '^https?://')
               OR (kind = 'group' AND url IS NULL)),
    CONSTRAINT fk_sand_system_menu_custom_created_by
        FOREIGN KEY (created_by) REFERENCES sand_system_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_sand_system_menu_custom_updated_by
        FOREIGN KEY (updated_by) REFERENCES sand_system_user (id) ON DELETE SET NULL
);
COMMENT ON TABLE sand_system_menu_custom IS '自建菜单（分组/外部链接）；url 仅是 link 类的网页导航地址';
CREATE INDEX ix_sand_system_menu_custom_parent_sort
    ON sand_system_menu_custom (parent_key, sort);

-- 系统设置。key 单列主键；value 用 jsonb 存任意 JSON 值；不存密钥
-- （云存储/邮件密钥行在升级迁移里删除，插件密钥放插件自己的表）。
CREATE TABLE sand_system_setting (
    key         varchar(64) PRIMARY KEY,
    value       jsonb       NOT NULL,
    group_code  varchar(32) NOT NULL,                       -- basic/login/users/watermark 等
    create_time timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE sand_system_setting IS '系统设置键值；value 为 jsonb；禁止存明文密钥';
CREATE INDEX ix_sand_system_setting_group_code ON sand_system_setting (group_code);

-- 字典组（选项组）。code/name 唯一；系统自带组不能删由 is_system 标记 + 应用层保证。
CREATE TABLE sand_system_dict_type (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    code         varchar(64) NOT NULL,                      -- 系统自动生成，界面不展示
    name         varchar(20) NOT NULL,
    remark       varchar(100) NULL,
    is_system    boolean     NOT NULL DEFAULT false,
    create_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by   bigint      NULL,
    updated_by   bigint      NULL,
    CONSTRAINT pk_sand_system_dict_type PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_dict_type_code UNIQUE (code),
    CONSTRAINT uk_sand_system_dict_type_name UNIQUE (name),
    CONSTRAINT fk_sand_system_dict_type_created_by
        FOREIGN KEY (created_by) REFERENCES sand_system_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_sand_system_dict_type_updated_by
        FOREIGN KEY (updated_by) REFERENCES sand_system_user (id) ON DELETE SET NULL
);
COMMENT ON TABLE sand_system_dict_type IS '选项组（数据字典分组）；删除时选项级联删除';

-- 字典选项。组内名称与值各自唯一；一组只能有一个默认选中（部分唯一索引）。
CREATE TABLE sand_system_dict_item (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    type_id      bigint      NOT NULL,
    label        varchar(20) NOT NULL,
    value        varchar(64) NOT NULL,                      -- 系统自动生成的存储值
    color        varchar(16) NULL,                          -- 8 个预设色之一，空为默认
    is_default   boolean     NOT NULL DEFAULT false,
    is_system    boolean     NOT NULL DEFAULT false,        -- 系统自带选项不能删
    status       smallint    NOT NULL DEFAULT 1,            -- 1 启用 / 2 停用
    sort         integer     NOT NULL DEFAULT 0,
    create_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by   bigint      NULL,
    updated_by   bigint      NULL,
    CONSTRAINT pk_sand_system_dict_item PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_dict_item_type_label UNIQUE (type_id, label),
    CONSTRAINT uk_sand_system_dict_item_type_value UNIQUE (type_id, value),
    CONSTRAINT ck_sand_system_dict_item_status CHECK (status IN (1, 2)),
    CONSTRAINT fk_sand_system_dict_item_type
        FOREIGN KEY (type_id) REFERENCES sand_system_dict_type (id) ON DELETE CASCADE,
    CONSTRAINT fk_sand_system_dict_item_created_by
        FOREIGN KEY (created_by) REFERENCES sand_system_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_sand_system_dict_item_updated_by
        FOREIGN KEY (updated_by) REFERENCES sand_system_user (id) ON DELETE SET NULL
);
COMMENT ON TABLE sand_system_dict_item IS '选项组里的选项；组内 label/value 唯一，一组一个默认';
-- 一组同时只能有一个默认选中
CREATE UNIQUE INDEX uk_sand_system_dict_item_default
    ON sand_system_dict_item (type_id) WHERE is_default;
