    CONSTRAINT ck_sand_system_plugin_version
        CHECK (version ~ '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$'),
    CONSTRAINT ck_sand_system_plugin_manifest_sha256
        CHECK (manifest_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sand_system_plugin_state CHECK (state IN ('installed', 'uninstalled'))
);
COMMENT ON TABLE sand_system_plugin IS '已安装插件登记；version 为 Semver，host_constraint 为声明的宿主兼容范围';

