-- 插件登记表：记录已装插件的版本与声明的宿主兼容范围。
-- 卸载不勾「删除数据」时保留 state='uninstalled' 行，重装恢复调整；
-- 勾选删除数据的卸载删除本行（级联清掉插件扩展位覆盖等残留）。
CREATE TABLE sand_system_plugin (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    code            varchar(64) NOT NULL,                   -- 例：sand-iam
    name            varchar(64) NOT NULL,
    version         varchar(32) NOT NULL,                   -- Semver
    host_constraint varchar(64) NOT NULL,                   -- 声明兼容的宿主范围，例：^1.2
    manifest_sha256 char(64)    NOT NULL,                   -- 安装包清单的 SHA-256
    state           varchar(16) NOT NULL DEFAULT 'installed',
    install_time    timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time     timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    uninstall_time  timestamptz(0) NULL,
    CONSTRAINT pk_sand_system_plugin PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_plugin_code UNIQUE (code),
    CONSTRAINT ck_sand_system_plugin_code
