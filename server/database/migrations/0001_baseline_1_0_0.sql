-- 四、任务（通用任务运行记录、定时任务状态与执行记录）
-- 库里不存可执行目标：只存状态、时间、payload（payload 不得含口令密钥，
-- 由应用层在写入前保证剔除）。

-- 通用任务运行记录（后台任务/申请执行进度共用的运行态表）。
CREATE TABLE sand_system_task_run (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    public_id         uuid         NOT NULL DEFAULT gen_random_uuid(),
    type              varchar(64)  NOT NULL,                -- 任务类型标识，来自清单
    payload           jsonb        NOT NULL DEFAULT '{}'::jsonb, -- 入参；不得含口令、密钥（应用层保证）
    state             varchar(16)  NOT NULL DEFAULT 'queued',
    stage             varchar(32)  NULL,                    -- 当前阶段的人话描述
    progress          smallint     NOT NULL DEFAULT 0,
    result            jsonb        NULL,                    -- 结果摘要；不得含敏感数据
    error_code        varchar(64)  NULL,
    error_message     varchar(500) NULL,
    created_by        bigint       NOT NULL,                -- 发起人
    idempotency_key   varchar(128) NULL,                    -- 幂等键；同类型同键全库只允许一条
    locked_by         varchar(128) NULL,                    -- 执行者标识（认领者）
    lease_expire_time timestamptz(0) NULL,                  -- 租约到期；崩溃后可被重新认领
    attempt           smallint     NOT NULL DEFAULT 0,
    start_time        timestamptz(0) NULL,
    finish_time       timestamptz(0) NULL,
    create_time       timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sand_system_task_run PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_task_run_public_id UNIQUE (public_id),
    CONSTRAINT ck_sand_system_task_run_state
        CHECK (state IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
    CONSTRAINT ck_sand_system_task_run_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_sand_system_task_run_attempt CHECK (attempt >= 0),
    CONSTRAINT fk_sand_system_task_run_created_by
        FOREIGN KEY (created_by) REFERENCES sand_system_user (id) ON DELETE RESTRICT
);
COMMENT ON TABLE sand_system_task_run IS '后台任务运行记录；库里只存状态与载荷，不存可执行目标';
-- 待处理队列（认领扫描）
CREATE INDEX ix_sand_system_task_run_queued
    ON sand_system_task_run (create_time, id) WHERE state = 'queued';
CREATE INDEX ix_sand_system_task_run_creator_time
    ON sand_system_task_run (created_by, create_time DESC);
CREATE INDEX ix_sand_system_task_run_lease
    ON sand_system_task_run (lease_expire_time) WHERE state = 'running';
-- 同一类型 + 幂等键全库只允许一条；旧行清理后键才释放
CREATE UNIQUE INDEX uk_sand_system_task_run_idempotency
    ON sand_system_task_run (type, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

-- 写接口幂等记录：同键同请求在有效期内重放首次结果；过期由清理任务删除。
-- user_id 为 NULL 表示匿名写操作（如登录）。
CREATE TABLE sand_system_idempotency_key (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id       bigint       NULL,                        -- 匿名写操作（如登录）为 NULL
    key           varchar(128) NOT NULL,                    -- Idempotency-Key 原文
    request_hash  char(64)     NOT NULL,                    -- 方法+路径+请求体 SHA-256
    response      jsonb        NULL,                        -- 首次响应快照；处理中为 NULL
    create_time   timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expire_time   timestamptz(0) NOT NULL,                  -- create_time + 24 小时
    CONSTRAINT pk_sand_system_idempotency_key PRIMARY KEY (id),
    CONSTRAINT uk_sand_system_idempotency_key_user_key
        UNIQUE NULLS NOT DISTINCT (user_id, key),
    CONSTRAINT ck_sand_system_idempotency_key_request_hash
        CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sand_system_idempotency_key_expire
        CHECK (expire_time > create_time),
    CONSTRAINT fk_sand_system_idempotency_key_user
        FOREIGN KEY (user_id) REFERENCES sand_system_user (id) ON DELETE CASCADE
);
COMMENT ON TABLE sand_system_idempotency_key IS '写接口幂等记录；同键同请求 24 小时内重放首次结果，过期由清理任务删除';
CREATE INDEX ix_sand_system_idempotency_key_expire_time
    ON sand_system_idempotency_key (expire_time);

-- 定时任务状态。任务定义（处理类、默认时间）来自签名静态清单，
-- 本表只存管理员可改的状态与上次/下次执行；plugin_code 为 NULL 表示宿主自带任务。
CREATE TABLE sand_system_schedule (
    code                varchar(128) PRIMARY KEY,            -- 插件标识 + 任务键，例：sand-iam.xxx / host.xxx
    plugin_code        varchar(64)  NULL,                   -- 宿主自带任务为 NULL
    enabled            boolean      NOT NULL DEFAULT true,
    schedule           jsonb        NULL,                   -- 管理员改过的时间结构；NULL 用清单默认
    last_run_time      timestamptz(0) NULL,
    last_run_succeeded boolean      NULL,                   -- NULL 表示还没有成功记录可判
    next_run_time      timestamptz(0) NULL,
    create_time        timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time        timestamptz(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sand_system_schedule_plugin_code
        CHECK (plugin_code IS NULL OR plugin_code ~ '^[a-z0-9][a-z0-9_-]{0,63}$'),
    CONSTRAINT fk_sand_system_schedule_plugin
        FOREIGN KEY (plugin_code) REFERENCES sand_system_plugin (code) ON DELETE CASCADE
);
COMMENT ON TABLE sand_system_schedule IS '定时任务状态；schedule 为 jsonb 时间结构（freq/interval/time/weekday/monthday），NULL 用清单默认';
CREATE INDEX ix_sand_system_schedule_plugin_code ON sand_system_schedule (plugin_code);

-- 定时任务执行记录。只增不改；保留 180 天。
-- 失败分两类：业务原因给人话 error_message；系统内部给 error_code + request_id
-- 供「复制问题信息」排查（error_code='interrupted' 表示进程中断被标记）。
CREATE TABLE sand_system_schedule_run (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    schedule_code   varchar(128) NOT NULL,
    trigger        varchar(8)   NOT NULL,                   -- schedule / manual
    start_time     timestamptz(0) NOT NULL,
    finish_time    timestamptz(0) NULL,
    succeeded      boolean      NULL,                       -- NULL 表示仍在执行/结果未知
    error_message  varchar(500) NULL,                       -- 失败原因（大白话）
    error_code     varchar(64)  NULL,                       -- 失败类别/排查码，interrupted=进程中断被标记
    request_id     varchar(64)  NULL,                       -- 排查用请求追踪编号
    CONSTRAINT pk_sand_system_schedule_run PRIMARY KEY (id),
    CONSTRAINT ck_sand_system_schedule_run_trigger CHECK (trigger IN ('schedule', 'manual')),
    -- 未结束则无结果；结束必有结果
    CONSTRAINT ck_sand_system_schedule_run_finish_state
        CHECK ((finish_time IS NULL) = (succeeded IS NULL)),
    CONSTRAINT ck_sand_system_schedule_run_finish_start
        CHECK (finish_time IS NULL OR finish_time >= start_time),
    CONSTRAINT fk_sand_system_schedule_run_schedule
        FOREIGN KEY (schedule_code) REFERENCES sand_system_schedule (code) ON DELETE CASCADE
);
COMMENT ON TABLE sand_system_schedule_run IS '定时任务执行记录；只增不改；保留 180 天；失败原因分人话 error_message 与排查码 error_code+request_id';
CREATE INDEX ix_sand_system_schedule_run_schedule_time
    ON sand_system_schedule_run (schedule_code, start_time DESC);
CREATE INDEX ix_sand_system_schedule_run_start_time
    ON sand_system_schedule_run (start_time);

