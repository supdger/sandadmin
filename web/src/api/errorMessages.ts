/** 未登记的码也给出带码的中文，避免页面只显示一个英文码。 */
export function messageForErrorCode(code: string): string {
  if (Object.prototype.hasOwnProperty.call(API_ERROR_MESSAGES, code)) {
    return API_ERROR_MESSAGES[code as ApiErrorCode];
  }
  return `系统出了点问题，请稍后再试（${code}）`;
}
